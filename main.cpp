/* 详细计划（伪代码）:
   1. 显示提示信息，要求用户输入两个整数。
   2. 从标准输入读取两个整数到变量 a 和 b。
   3. 计算 a 和 b 的和，存到临时表达式或直接输出。
   4. 将结果输出到标准输出，附带说明文字。
   5. 返回 0 表示程序正常结束。
   注：此处仅为注释说明，不改变原始程序逻辑。若需增强健壮性，可在读取后检查输入有效性。
*/

#include <iostream>          // 包含输入输出流库
using namespace std;         // 使用标准命名空间，方便使用 cout / cin 等

int main() {
	// 定义两个整型变量 a 和 b，用于存放用户输入的两个数字
	int a, b;

	// 提示用户输入两个数字（不换行，等待用户输入）
	cout << "Enter two numbers: ";

	// 从标准输入读取两个整数，按空白分隔（空格或换行都可）
	cin >> a >> b;

	// 输出两个数字的和，endl 用于换行并刷新输出缓冲区
	cout << "The sum is: " << a + b << endl;

	// 返回 0 表示程序成功结束
	return 0;
}